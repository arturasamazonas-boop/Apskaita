-- Group (header) accounts never receive postings, enforced in the database as well.
CREATE FUNCTION journal_line_postable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM accounts WHERE code=NEW.account_code AND NOT postable) THEN
    RAISE EXCEPTION 'Sąskaita % yra grupė – į ją kontuoti negalima', NEW.account_code USING ERRCODE='check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER journal_lines_postable BEFORE INSERT ON journal_lines FOR EACH ROW EXECUTE FUNCTION journal_line_postable();
